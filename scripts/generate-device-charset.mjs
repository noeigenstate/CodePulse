// Only reads firmware; the desktop artifact is the sole generated output.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const source = new URL('../firmware/fonts/sources/noto-hierarchy.json', import.meta.url)
const target = new URL('../apps/desktop/src/main/device-charset.generated.ts', import.meta.url)
const { codes } = JSON.parse(readFileSync(source, 'utf8'))
if (
  !Array.isArray(codes) ||
  codes.some(
    (code, i) =>
      !Number.isInteger(code) ||
      code < 0 ||
      code > 0x10ffff ||
      (code >= 0xd800 && code <= 0xdfff) ||
      (i > 0 && code <= codes[i - 1]),
  )
)
  throw Error('Expected sorted unique Unicode scalar values in firmware font codes')
const chunks = []
for (let i = 0; i < codes.length; i += 80)
  chunks.push(JSON.stringify(String.fromCodePoint(...codes.slice(i, i + 80))))
const output =
  '// Generated by node scripts/generate-device-charset.mjs; do not edit.\n' +
  '// Source: firmware/fonts/sources/noto-hierarchy.json (codes).\n' +
  `// ${codes.length} Unicode code points; glyph data and firmware are unchanged.\n` +
  'export const DEVICE_CHARACTERS =\n  ' +
  chunks.join(' +\n  ') +
  '\n'
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output)
    throw Error('Device character set drifted; run node scripts/generate-device-charset.mjs')
} else writeFileSync(target, output)
console.log(
  `${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${codes.length} device code points: ${fileURLToPath(target)}`,
)
