"""Native Terminus32 and supersampled native Noto56/60 subsets and the approved B study's exact 2bpp icons.

Stdlib packing only; pinned dev-only hero rasterization is a separate stage.
Run from any directory; --check is read-only. Original font/license bytes stay intact.
"""
import argparse
import gzip
import hashlib
import json
import runpy
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FONT_SHA = 'c976e4b1b99edc88775377fcc21692ca4bfa46b6d6ca6522bfda505b28ff9d6a'
CHARS = list(range(32,127)) + [176,183,0x2013,0x2212]
NUMBERS = set(map(ord,'0123456789.:%+-/')) | {176,0x2013,0x2212}
STRIKES = [('MID','terminus-32b',set(CHARS)),('HERO','hero-56',NUMBERS),('WEATHER','hero-60',NUMBERS)]
SPACING=runpy.run_path(str(Path(__file__).with_name('font-spacing.py')))

def crop(a,l,t,w,h,bits):
    points=[(x,y) for y in range(h) for x in range(w) if bits[y*((w+7)//8)+x//8]&(128>>(x%8))]
    if not points:return (a,0,0,0,0,b'')
    x0=min(x for x,y in points);y0=min(y for x,y in points);w1=max(x for x,y in points)-x0+1;h1=max(y for x,y in points)-y0+1
    out=bytearray((w1+7)//8*h1)
    for x,y in points:out[(y-y0)*((w1+7)//8)+(x-x0)//8]|=128>>((x-x0)%8)
    return a,l+x0,t+y0,w1,h1,bytes(out)

def build():
    folder=ROOT/'fonts/sources'
    source=json.loads((folder/'grid-native-masks.json').read_text(encoding='utf-8'))
    raw=gzip.decompress((folder/'grid-native-masks.bin.gz').read_bytes())
    if hashlib.sha256(raw).hexdigest()!=source['atlasSha256']:raise ValueError('Source masks changed')
    font_pixels=bytearray();font_tables=[]
    for name,face_name,points in STRIKES:
        face=next(f for f in source['faces'] if f['name']==face_name);table=[]
        for cp in CHARS:
            if cp not in points:table.append((0,0,0,0,0,0));continue
            actual=0x2013 if cp==0x2212 and face_name=='terminus-32b' else cp
            p,a,l,t,w,h=struct.unpack_from('<IHbbBB',raw,face['offset']+face['codes'].index(actual)*10)
            a,l,t,w,h,bits=crop(a//64,l,t,w,h,raw[p:p+(w+7)//8*h])
            if name=='MID':a,l,t,w,h,bits=SPACING['terminus_spacing'](cp,(a,l,t,w,h,bits))
            table.append((len(font_pixels),a,l,t,w,h));font_pixels.extend(bits)
        font_tables.append(table)
    if len(font_pixels)>65535:raise ValueError('Life font offset overflow')
    icons_path = ROOT / 'preview/life-icons.json'
    icons = json.loads(icons_path.read_text(encoding='utf-8'))
    names, descriptors, packed = [], [], []
    for group, entries in icons.items():
        size = {'hero48': 48, 'inline16': 16, 'arrow24': 24}[group]
        for name, rows in entries.items():
            if len(rows) != size or any(len(row) != size or set(row) - set('.#Ro') for row in rows):
                raise ValueError('Invalid approved icon: ' + name)
            names.append('LIFE_ICON_' + group.upper() + '_' + name.upper())
            descriptors.append((len(packed), size))
            values = [{'.': 0, '#': 1, 'R': 2, 'o': 3}[pixel] for row in rows for pixel in row]
            packed.extend(sum(values[i+j] << (6-2*j) for j in range(4)) for i in range(0, len(values), 4))
    if len(packed) > 65535:
        raise ValueError('Icon offsets exceed their bounded uint16 table')
    header = [
        '/* Generated by scripts/generate-life-assets.py. Do not edit.',
        ' * Terminus32: Copyright (C) 2020 Dimitar Toshkov Zhekov; Noto: Copyright Google LLC; SIL OFL-1.1.',
        ' * Source SHA256: ' + FONT_SHA,
        ' * Icons: exact pixels from the approved yb-life-v1 / variant B study. */',
        '#pragma once', '#include <stdint.h>',
        'enum { ' + ', '.join(names) + ', LIFE_ICON_COUNT };',
        'typedef struct { uint16_t offset; uint8_t size; } life_icon_info_t;',
        'static const life_icon_info_t life_icons[] = {',
        ',\n'.join('  {%d,%d}' % item for item in descriptors), '};',
        'static const uint8_t life_icon_pixels[] = {',
        ',\n'.join('  ' + ','.join('0x%02x' % v for v in packed[i:i+24]) for i in range(0, len(packed), 24)), '};',
        'static const uint32_t life_font_codes[] = {' + ','.join(str(code) for code in CHARS) + '};',
        'typedef struct { uint16_t offset; uint8_t advance; int8_t left,top; uint8_t width,height; } life_font_glyph_t;',
        'static const life_font_glyph_t life_font_glyphs[][%d] = {' % len(CHARS),
        ',\n'.join('  {'+','.join('{'+','.join(map(str,g))+'}' for g in table)+'}' for table in font_tables), '};',
        'static const uint8_t life_font_bits[] = {',
        ',\n'.join('  '+','.join('0x%02x'%v for v in font_pixels[i:i+24]) for i in range(0,len(font_pixels),24)), '};',
        '#define LIFE_FONT_GLYPHS %d' % len(CHARS),
        '#define LIFE_FONT_MID 0','#define LIFE_FONT_HERO 1','#define LIFE_FONT_WEATHER 2','',
    ]
    metadata={'source':'fonts/sources/NotoSans-Bold.ttf','sha256':FONT_SHA,'license':'fonts/licenses/NotoSans-2.008-OFL.txt',
        'midSource':'fonts/sources/terminus-ter-u32b.bdf.gz','midSha256':source['sourceHashes']['terminus-ter-u32b.bdf.gz'],
        'sourceMasksSha256':source['atlasSha256'],'recipe':source['recipe'],'spacing':SPACING['POLICY'],
        'strikes':[{'name':name,'sourceFace':face,'nativeSize':32 if name=='MID' else 56 if name=='HERO' else 60,'codes':sorted(points)} for name,face,points in STRIKES],
        'iconsSource':'preview/life-icons.json','iconsSha256':hashlib.sha256(icons_path.read_bytes()).hexdigest(),
        'glyphCodes':CHARS,'icons':len(names),'iconBytes':len(packed),'fontBitmapBytes':len(font_pixels),
        'fontCodeBytes':len(CHARS)*4,'fontDescriptorBytes':len(CHARS)*len(STRIKES)*8,'iconDescriptorBytes':len(names)*4}
    return '\n'.join(header), json.dumps(metadata, indent=2) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    values = build()
    for path, value in zip([ROOT/'main/life_assets.generated.h', ROOT/'fonts/sources/life-assets.json'], values):
        if args.check:
            if path.read_text(encoding='utf-8') != value:
                raise SystemExit('Stale generated life asset: ' + str(path))
        else:
            path.write_text(value, encoding='utf-8', newline='\n')
    print(('Verified' if args.check else 'Generated') + ' pinned life font and exact icon pixels')


if __name__ == '__main__':
    main()
