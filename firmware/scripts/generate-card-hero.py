"""32px CJK strike for the reading cards' large lines (concept term, prompt question).

Two stages, like the life assets:
  python generate-card-hero.py --rasterize   (dev only; Pillow + FreeType) renders each code
      point of fonts/sources/card-hero-charset.txt from Noto Sans SC Regular at its native 32px
      size into fonts/sources/card-hero-masks.json. Recipe: 8x supersampling with a 3/8 px
      outline (a medium weight), one coverage threshold at 50%, no integer upscaling.
  python generate-card-hero.py [--check]     (stdlib only) packs those masks into
      main/card_hero.generated.h; --check is read-only and fails on a stale header.
A code point outside the charset never reaches this strike: the firmware draws that whole line
with the native 16px face instead. The source font is SIL OFL 1.1 (fonts/licenses).
"""
import argparse
import hashlib
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'fonts/sources/NotoSansSC-Regular.otf'
SOURCE_SHA = 'faa6c9df652116dde789d351359f3d7e5d2285a2b2a1f04a2d7244df706d5ea9'
CHARSET = ROOT / 'fonts/sources/card-hero-charset.txt'
MASKS = ROOT / 'fonts/sources/card-hero-masks.json'
HEADER = ROOT / 'main/card_hero.generated.h'
SIZE, SUPERSAMPLE, OUTLINE, THRESHOLD = 32, 8, 3, 0.5


def charset():
    text = CHARSET.read_text(encoding='utf-8')
    codes = sorted({ord(c) for c in text if not c.isspace()})
    if not codes or any(c < 0x80 for c in codes):
        raise SystemExit('The hero charset holds only non-ASCII characters (ASCII stays native).')
    return codes


def rasterize():
    from PIL import Image, ImageDraw, ImageFont  # dev-only stage
    import numpy as np
    data = SOURCE.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SOURCE_SHA:
        raise SystemExit('Unexpected Noto Sans SC source')
    # FreeType cannot open non-ASCII paths on Windows; load from memory.
    big = ImageFont.truetype(io.BytesIO(data), SIZE * SUPERSAMPLE)
    native = ImageFont.truetype(io.BytesIO(data), SIZE)
    glyphs = []
    for cp in charset():
        ch = chr(cp)
        if big.getmask(ch).getbbox() is None:
            raise SystemExit(f'Noto Sans SC has no glyph for U+{cp:04X}')
        s = SIZE * SUPERSAMPLE
        image = Image.new('L', (2 * s, 2 * s), 0)
        # Baseline at (s/2, s*1.5) in the oversized canvas; the outline adds weight evenly.
        ImageDraw.Draw(image).text((s // 2, s + s // 2), ch, font=big, fill=255, anchor='ls',
                                   stroke_width=OUTLINE, stroke_fill=255)
        a = np.asarray(image, np.float32) / 255
        n = 2 * SIZE
        cover = a.reshape(n, SUPERSAMPLE, n, SUPERSAMPLE).mean((1, 3)) >= THRESHOLD
        ys, xs = np.nonzero(cover)
        if not len(xs):
            raise SystemExit(f'U+{cp:04X} has no ink at 32px')
        x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
        rows = []
        for y in range(y0, y1):
            bits = 0
            for x in range(x0, x1):
                bits = bits << 1 | int(cover[y, x])
            rows.append(format(bits << ((8 - (x1 - x0) % 8) % 8), 'x').zfill(((x1 - x0 + 7) // 8) * 2))
        glyphs.append({
            'code': cp,
            'advance': round(native.getlength(ch)),
            'left': int(x0) - SIZE // 2,
            'top': int(y0) - (SIZE + SIZE // 2),
            'width': int(x1 - x0),
            'height': int(y1 - y0),
            'rows': rows,
        })
    metadata = {
        'source': 'fonts/sources/NotoSansSC-Regular.otf',
        'sha256': digest,
        'license': 'fonts/licenses/NotoSansSC-2.004-OFL.txt',
        'recipe': {'size': SIZE, 'supersample': SUPERSAMPLE, 'outlineSupersampledPx': OUTLINE,
                   'threshold': THRESHOLD, 'scaling': 'none'},
        'glyphs': glyphs,
    }
    MASKS.write_text(json.dumps(metadata, ensure_ascii=False, indent=1) + '\n', encoding='utf-8', newline='\n')
    print('Rasterized', len(glyphs), 'hero glyphs')


def pack():
    masks = json.loads(MASKS.read_text(encoding='utf-8'))
    glyphs = masks['glyphs']
    if [g['code'] for g in glyphs] != charset():
        raise SystemExit('card-hero-masks.json does not match the charset: run --rasterize')
    bits, table = bytearray(), []
    for g in glyphs:
        stride = (g['width'] + 7) // 8
        if len(g['rows']) != g['height'] or any(len(r) != stride * 2 for r in g['rows']):
            raise SystemExit(f"Malformed mask U+{g['code']:04X}")
        table.append((g['code'], len(bits), g['advance'], g['left'], g['top'], g['width'], g['height']))
        for r in g['rows']:
            bits.extend(bytes.fromhex(r))
    lines = [
        '/* Generated by scripts/generate-card-hero.py. Do not edit.',
        ' * Noto Sans SC Regular, native 32px (8x supersampled, 3/8px outline, 50% threshold).',
        ' * Noto Sans SC (c) 2014-2021 Adobe (http://www.adobe.com/), SIL OFL-1.1.',
        ' * Source SHA256: ' + masks['sha256'] + ' */',
        '#pragma once',
        '#include <stdint.h>',
        'typedef struct { uint32_t code; uint32_t offset; uint8_t advance; int8_t left, top; uint8_t width, height; } card_hero_glyph_t;',
        '#define CARD_HERO_GLYPHS %d' % len(table),
        '#define CARD_HERO_SIZE %d' % SIZE,
        '/* Sorted by code point for binary search. */',
        'static const card_hero_glyph_t card_hero_glyphs[CARD_HERO_GLYPHS] = {',
        ',\n'.join('  {%d,%d,%d,%d,%d,%d,%d}' % t for t in table),
        '};',
        'static const uint8_t card_hero_bits[] = {',
        ',\n'.join('  ' + ','.join('0x%02x' % v for v in bits[i:i + 24]) for i in range(0, len(bits), 24)),
        '};',
        '',
    ]
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--rasterize', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.rasterize:
        rasterize()
    value = pack()
    if args.check:
        if HEADER.read_text(encoding='utf-8') != value:
            raise SystemExit('Stale generated card hero strike: ' + str(HEADER))
        print('Verified card hero strike')
    else:
        HEADER.write_text(value, encoding='utf-8', newline='\n')
        print('Generated card hero strike')


if __name__ == '__main__':
    main()
