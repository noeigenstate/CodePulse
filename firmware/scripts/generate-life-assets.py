"""Pinned Terminus Bold32 subset and the approved B study's exact 2bpp icons.

No rasterizer, system font, hand-entered glyph, antialiasing or network is used.
Run from any directory; --check is read-only. Original font/license bytes stay intact.
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'fonts/sources/terminus-ter-u32b.bdf.gz'
FONT_SHA = '9bf7c8feb04601ed162e81f8e73dfccde946374f5dfa85395aaa7bab0cb714b0'
CHARS = list(range(32, 127)) + [176, 0x2212]


def build():
    raw = FONT.read_bytes()
    if hashlib.sha256(raw).hexdigest() != FONT_SHA:
        raise ValueError('Pinned Terminus Bold32 source hash changed')
    glyphs = {}
    current = None
    bitmap = False
    for line in gzip.decompress(raw).decode('ascii').splitlines():
        if line.startswith('STARTCHAR '):
            current = {'rows': []}
        elif line.startswith('ENCODING '):
            current['code'] = int(line.split()[1])
        elif line.startswith('DWIDTH '):
            current['advance'] = int(line.split()[1])
        elif line.startswith('BBX '):
            current['box'] = list(map(int, line.split()[1:]))
        elif line == 'BITMAP':
            bitmap = True
        elif line == 'ENDCHAR':
            glyphs[current['code']] = current
            bitmap = False
        elif bitmap:
            current['rows'].append(int(line, 16))
    selected = []
    for code in CHARS:
        g = glyphs[code]
        if g['box'] != [16, 32, 0, -6] or g['advance'] != 16 or len(g['rows']) != 32:
            raise ValueError('Unexpected native BDF cell geometry')
        selected.append(g)
    icons_path = ROOT / 'preview/life-icons.json'
    icons = json.loads(icons_path.read_text(encoding='utf-8'))
    names, descriptors, packed = [], [], []
    for group, entries in icons.items():
        size = {'hero48': 48, 'inline16': 16, 'arrow24': 24}[group]
        for name, rows in entries.items():
            if len(rows) != size or any(len(row) != size or set(row) - set('.#Ro') for row in rows):
                raise ValueError('Invalid approved icon: ' + name)
            names.append('LIFE_ICON_' + group.upper() + '_' + name.upper())
            descriptors.append((len(packed), size))
            values = [{'.': 0, '#': 1, 'R': 2, 'o': 3}[pixel] for row in rows for pixel in row]
            packed.extend(sum(values[i+j] << (6-2*j) for j in range(4)) for i in range(0, len(values), 4))
    if len(packed) > 65535:
        raise ValueError('Icon offsets exceed their bounded uint16 table')
    header = [
        '/* Generated by scripts/generate-life-assets.py. Do not edit.',
        ' * Terminus: Copyright (C) 2020 Dimitar Toshkov Zhekov; SIL OFL-1.1.',
        ' * Source SHA256: ' + FONT_SHA,
        ' * Icons: exact pixels from the approved yb-life-v1 / variant B study. */',
        '#pragma once', '#include <stdint.h>',
        'enum { ' + ', '.join(names) + ', LIFE_ICON_COUNT };',
        'typedef struct { uint16_t offset; uint8_t size; } life_icon_info_t;',
        'static const life_icon_info_t life_icons[] = {',
        ',\n'.join('  {%d,%d}' % item for item in descriptors), '};',
        'static const uint8_t life_icon_pixels[] = {',
        ',\n'.join('  ' + ','.join('0x%02x' % v for v in packed[i:i+24]) for i in range(0, len(packed), 24)), '};',
        'static const uint32_t life_font_codes[] = {' + ','.join(str(code) for code in CHARS) + '};',
        'static const uint16_t life_font_rows[][32] = {',
        ',\n'.join('  {' + ','.join('0x%04x' % row for row in g['rows']) + '}' for g in selected), '};',
        '#define LIFE_FONT_GLYPHS %d' % len(CHARS),
        '#define LIFE_FONT_ADVANCE 16', '#define LIFE_FONT_TOP (-26)', '',
    ]
    metadata = {'source': 'fonts/sources/terminus-ter-u32b.bdf.gz', 'sha256': FONT_SHA,
                'license': 'fonts/licenses/Terminus-OFL.txt',
                'iconsSource': 'preview/life-icons.json', 'iconsSha256': hashlib.sha256(icons_path.read_bytes()).hexdigest(),
                'glyphCodes': CHARS, 'icons': len(names), 'iconBytes': len(packed),
                'fontBitmapBytes': len(CHARS)*32*2, 'fontCodeBytes': len(CHARS)*4,
                'iconDescriptorBytes': len(names)*4}
    return '\n'.join(header), json.dumps(metadata, indent=2) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    values = build()
    for path, value in zip([ROOT/'main/life_assets.generated.h', ROOT/'fonts/sources/life-assets.json'], values):
        if args.check:
            if path.read_text(encoding='utf-8') != value:
                raise SystemExit('Stale generated life asset: ' + str(path))
        else:
            path.write_text(value, encoding='utf-8', newline='\n')
    print(('Verified' if args.check else 'Generated') + ' pinned life font and exact icon pixels')


if __name__ == '__main__':
    main()
